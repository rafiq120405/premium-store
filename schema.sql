-- 1. TABEL ORDERS (Menyimpan riwayat transaksi pembelian)
create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  order_id text not null,
  product text not null,
  variant text not null,
  price numeric not null,
  customer_email text,
  notes text,
  status text default 'pending_payment',
  created_at timestamp with time zone default timezone('utc'::text, now())
);

-- Mengaktifkan Row Level Security (RLS) pada tabel orders
alter table public.orders enable row level security;

-- Policy: Izinkan siapa saja (anonim/user) memasukkan pesanan baru
create policy "Allow insert orders" on public.orders
  for insert with check (true);

-- Policy: Izinkan membaca pesanan
create policy "Allow read orders" on public.orders
  for select using (true);


-- 2. TABEL PRODUCTS (Opsional: jika ingin mengelola katalog produk langsung dari Supabase)
create table if not exists public.products (
  id text primary key,
  name text not null,
  badge text,
  icon text,
  "bgColor" text,
  description text,
  variants jsonb default '[]'::jsonb,
  created_at timestamp with time zone default timezone('utc'::text, now())
);

-- Mengaktifkan Row Level Security (RLS) pada tabel products
alter table public.products enable row level security;

-- Policy: Izinkan siapa saja membaca katalog produk
create policy "Allow public read products" on public.products
  for select using (true);

